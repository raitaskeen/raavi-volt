// Generates db/seed.sql from db/seed-data.ts. Run: `bun run db:seed:gen`
import { writeFileSync } from "node:fs";
import { seedProducts } from "../db/seed-data";
import { slugify } from "../src/lib/utils";

const q = (v: string | number | null | undefined) =>
  v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`;

const now = Math.floor(Date.now() / 1000);
const lines = seedProducts.map((p, i) => {
  const slug = slugify(p.name);
  const sku = `RV-${p.category.slice(0, 3).toUpperCase()}-${String(i + 1).padStart(3, "0")}`;
  const specs = JSON.stringify(p.specs.map(([label, value]) => ({ label, value })));
  // Stagger timestamps so "newest" sorting is deterministic.
  const ts = now - i * 3600;
  return `INSERT OR IGNORE INTO products (id, slug, name, brand, category, sku, price, compare_at, stock, short_desc, description, specs, images, warranty, featured, active, created_at, updated_at) VALUES (${[
    q(crypto.randomUUID()),
    q(slug),
    q(p.name),
    q(p.brand),
    q(p.category),
    q(sku),
    q(p.price),
    q(p.compareAt ?? null),
    q(p.stock),
    q(p.short),
    q(p.description),
    q(specs),
    q("[]"),
    q(p.warranty ?? null),
    p.featured ? 1 : 0,
    1,
    ts,
    ts,
  ].join(", ")});`;
});

writeFileSync("db/seed.sql", `-- Generated by scripts/gen-seed.ts — do not edit by hand.\n${lines.join("\n")}\n`);
console.log(`Wrote ${lines.length} products to db/seed.sql`);
