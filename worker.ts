/**
 * Worker entry: wraps the OpenNext handler with an edge page cache.
 *
 * Public, data-backed pages (home, shop, product, info pages and their client
 * navigation RSC payloads) are served from the Cloudflare Cache API. The key
 * includes a catalog version that a D1 trigger bumps on every product change,
 * so edits and stock changes show up immediately everywhere. Admin, cart,
 * checkout, order and API routes always go to the app.
 *
 * Cache API is only available on a custom domain, so on *.workers.dev this is
 * a transparent pass-through.
 */
import type { D1Database, ExecutionContext } from "@cloudflare/workers-types";
// @ts-ignore — generated by `opennextjs-cloudflare build`
import { default as handler } from "./.open-next/worker.js";

type Env = { DB: D1Database } & Record<string, unknown>;

const CACHEABLE: { re: RegExp; ttl: number }[] = [
  { re: /^\/$/, ttl: 600 },
  { re: /^\/shop$/, ttl: 600 },
  { re: /^\/product\/[\w-]+$/, ttl: 600 },
  { re: /^\/(about|contact|shipping-returns|privacy|terms|track)$/, ttl: 3600 },
  { re: /^\/sitemap\.xml$/, ttl: 3600 },
];
/** Serve a stale copy (and refresh in the background) for up to a day. */
const STALE_FOR = 86_400;
const TRACKING = /^(utm_|fbclid$|gclid$|ttclid$|mc_|_ga$)/;
const VERSION_TTL_MS = 15_000;

let version: { value: number; at: number } | null = null;

async function catalogVersion(db: D1Database) {
  if (version && Date.now() - version.at < VERSION_TTL_MS) return version.value;
  try {
    const row = await db.prepare("SELECT value FROM cache_meta WHERE key = 'catalog'").first<{ value: number }>();
    version = { value: row?.value ?? 0, at: Date.now() };
  } catch {
    version = { value: 0, at: Date.now() };
  }
  return version.value;
}

function cacheRule(request: Request, url: URL) {
  if (request.method !== "GET") return null;
  if (url.hostname.endsWith(".workers.dev") || url.hostname === "localhost" && !url.searchParams.has("__cache")) return null;
  // Signed-in admins always see live pages.
  if (/(^|;\s*)(__Host-)?rv_admin=/.test(request.headers.get("cookie") ?? "")) return null;
  const isRsc = request.headers.get("rsc") === "1";
  // RSC requests are only cacheable with Next's `_rsc` cache-busting param,
  // which encodes the router headers the response varies on.
  if (isRsc && !url.searchParams.has("_rsc")) return null;
  return CACHEABLE.find((r) => r.re.test(url.pathname)) ?? null;
}

function cacheKey(url: URL, v: number) {
  const key = new URL(url.toString());
  for (const name of [...key.searchParams.keys()]) if (TRACKING.test(name) || name === "__cache") key.searchParams.delete(name);
  key.searchParams.sort();
  key.searchParams.set("__v", String(v));
  return new Request(key.toString(), { method: "GET" });
}

function storable(res: Response) {
  const type = res.headers.get("content-type") ?? "";
  return res.status === 200 && !res.headers.has("set-cookie") && /text\/html|text\/x-component|xml/.test(type);
}

function forCache(res: Response) {
  const copy = new Response(res.body, res);
  copy.headers.set("Cache-Control", `public, s-maxage=${STALE_FOR}`);
  copy.headers.set("x-rv-cached-at", String(Math.floor(Date.now() / 1000)));
  return copy;
}

function forClient(res: Response, status: "HIT" | "STALE" | "MISS") {
  const out = new Response(res.body, res);
  // Browsers must revalidate; the edge holds the copy.
  out.headers.set("Cache-Control", "public, max-age=0, must-revalidate");
  out.headers.delete("x-rv-cached-at");
  out.headers.set("x-rv-cache", status);
  return out;
}

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const rule = cacheRule(request, url);
    const cache = (globalThis as unknown as { caches?: { default?: Cache } }).caches?.default;
    if (!rule || !cache) return handler.fetch(request, env, ctx);

    const key = cacheKey(url, await catalogVersion(env.DB));
    const cached = await cache.match(key);
    if (cached) {
      const age = Math.floor(Date.now() / 1000) - Number(cached.headers.get("x-rv-cached-at") ?? 0);
      if (age < rule.ttl) return forClient(cached, "HIT");
      if (age < STALE_FOR) {
        // Stale-while-revalidate: answer instantly, refresh for the next visitor.
        ctx.waitUntil(
          (async () => {
            const fresh: Response = await handler.fetch(new Request(request.url, { headers: request.headers }), env, ctx);
            if (storable(fresh)) await cache.put(key, forCache(fresh));
          })(),
        );
        return forClient(cached, "STALE");
      }
    }

    const res: Response = await handler.fetch(request, env, ctx);
    if (!storable(res)) return res;
    const [a, b] = res.body ? res.body.tee() : [null, null];
    ctx.waitUntil(cache.put(key, forCache(new Response(b, res))));
    return forClient(new Response(a, res), "MISS");
  },
};
